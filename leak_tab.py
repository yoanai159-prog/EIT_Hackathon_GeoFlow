"""Streamlit tab: early leak detection from the minimum night flow of each supply zone (SIMULATED data)."""
from pathlib import Path

import pandas as pd
import streamlit as st

import ui

from core.leaks import LeakSettings, analyse_zone, explain_leak

STATUS_TEXT = {"normal": "Normal", "watch": "Watch", "suspected_leak": "Suspected leak",
               "insufficient_data": "Not enough data"}


def render(data_dir: Path, settlements: pd.DataFrame, links: pd.DataFrame):
    st.subheader("Early leak detection (SIMULATED flow data)")
    st.warning("DEMO DATA: the hourly inflows, the zones (the invented settlements of the simulated network) and the leaks in them are "
               "generated by `generate_leak_data.py`. They are NOT measurements and have nothing to do with Shumen or Ticha. "
               "The page shows the method (minimum night flow), which would work the same way on real meter data from a water utility (ViK).")
    st.caption("Between 02:00 and 04:00 almost nobody uses water, so the inflow to a zone is mostly leakage. "
               "A leak shows up as a persistent rise of this minimum night flow above the zone's own recent normal.")

    path = data_dir / "flow_observations.csv"
    if not path.exists():
        st.info("No flow data yet. Run `python generate_leak_data.py` and reload.")
        return
    flow = pd.read_csv(path, parse_dates=["ts"])

    with st.expander("Detection settings"):
        c1, c2, c3 = st.columns(3)
        z = c1.slider("Sensitivity: robust z threshold", 2.0, 6.0, 3.0, 0.5)
        rel = c2.slider("Minimum rise over normal (%)", 5, 50, 15) / 100.0
        conf = c3.slider("Days in a row to confirm", 1, 7, 3)
    s = LeakSettings(z_threshold=z, min_excess_rel=rel, confirm_days=conf)

    names = settlements.set_index("settlement_id")["name"].to_dict()
    demand = links.groupby("settlement_id")["daily_demand_m3"].sum().to_dict()

    results, dets = [], {}
    for zid, g in flow.groupby("settlement_id"):
        det, res = analyse_zone(g[["ts", "inflow_m3_h"]], s)
        dets[zid] = det
        results.append({
            "zone": names.get(zid, str(zid)), "status": STATUS_TEXT[res["status"]],
            "normal night flow (m3/h)": None if res["baseline_m3h"] is None else round(res["baseline_m3h"], 2),
            "leak estimate (m3/h)": round(res["leak_m3h"], 2), "lost (m3/day)": round(res["lost_m3_day"], 1),
            "share of daily demand (%)": round(100 * res["lost_m3_day"] / demand[zid], 1) if demand.get(zid) else None,
            "since": res["since"], "_id": zid, "_res": res,
        })
    table = pd.DataFrame(results).sort_values("lost (m3/day)", ascending=False)

    m1, m2, m3 = st.columns(3)
    m1.metric("Zones monitored", len(table))
    m2.metric("Suspected leaks", int((table["status"] == STATUS_TEXT["suspected_leak"]).sum()))
    m3.metric("Estimated water lost (m3/day)", f"{table['lost (m3/day)'].sum():.0f}")

    st.dataframe(table.drop(columns=["_id", "_res"]), use_container_width=True, hide_index=True)

    pick = st.selectbox("Zone", table["zone"])
    row = table[table["zone"] == pick].iloc[0]
    zid, res = row["_id"], row["_res"]
    text = explain_leak(pick, res, demand.get(zid))
    {"suspected_leak": st.error, "watch": st.warning}.get(res["status"], st.success)(text)

    det = dets[zid]
    left, right = st.columns(2)
    left.markdown("**Minimum night flow vs normal (m3/h)**")
    ui.chart("line", det[["mnf", "baseline"]].rename(columns={"mnf": "minimum night flow", "baseline": "normal (baseline)"}),
             "date (day)", "minimum night flow, 02:00 to 04:00 (m3/h)", "SIMULATED flow data (generate_leak_data.py)")
    last7 = flow[(flow["settlement_id"] == zid) & (flow["ts"] >= flow["ts"].max() - pd.Timedelta(days=7))]
    right.markdown("**Hourly inflow, last 7 days (m3/h)**")
    ui.chart("line", last7.set_index("ts")["inflow_m3_h"].rename("inflow"), "time (hour)", "inflow to the zone (m3/h)",
             "SIMULATED flow data (generate_leak_data.py)")

    st.caption(
        "A zone is flagged when its night flow is at least the chosen number of robust standard deviations and "
        "the chosen percentage above its own normal, for the chosen number of days in a row. Days that look like "
        "a leak are kept out of the normal, so a slow leak cannot hide. Night irrigation, tank refilling or a real "
        "change in demand can look like a leak; the loss estimate is approximate because leakage depends on pressure. "
        "Real use needs an inflow meter per zone with hourly data."
    )
