"""Simulated demo of the generic chain (several invented reservoirs, settlements ranking, leak detection)."""
from pathlib import Path

import pandas as pd
import streamlit as st

import ui

from core.logic import ALERT_ORDER, Settings, explain, forecast, reservoir_status, settlement_risk
from leak_tab import render as render_leaks


@st.cache_data
def load(data_dir: str):
    d = Path(data_dir)
    return (pd.read_csv(d / "reservoirs.csv"), pd.read_csv(d / "reservoir_observations.csv", parse_dates=["obs_date"]),
            pd.read_csv(d / "settlements.csv"), pd.read_csv(d / "supply_links.csv"))


def render(data_dir: Path, settings: Settings):
    st.subheader("Simulated network (invented names and numbers)")
    st.warning("Everything on this page is SIMULATED (generated by `generate_data.py` and `generate_leak_data.py`): invented reservoirs, "
               "settlements, supply links and flows, outside the pilot territory. It shows the generic chain and the leak detection method, "
               "not real conditions.")
    reservoirs, observations, settlements, links = load(str(data_dir))
    status = {}
    for _, r in reservoirs.iterrows():
        o = observations[observations["reservoir_id"] == r["reservoir_id"]]
        status[int(r["reservoir_id"])] = reservoir_status(o, r["total_capacity_m3"], settings)
    alerts = {rid: s["alert_level"] for rid, s in status.items()}
    weeks = {rid: s["weeks_to_threshold"] for rid, s in status.items()}
    risk = settlement_risk(settlements, links, alerts, weeks, settings)
    res_table = reservoirs.assign(
        alert=[alerts[int(i)] for i in reservoirs["reservoir_id"]],
        fill_pct=[round(status[int(i)]["fill_pct"], 1) for i in reservoirs["reservoir_id"]],
        norm_pct=[round(status[int(i)]["norm_pct"], 1) for i in reservoirs["reservoir_id"]],
        deviation_pp=[round(status[int(i)]["deviation_pp"], 1) for i in reservoirs["reservoir_id"]],
        decline_pp_week=[round(status[int(i)]["rate_pp_week"], 2) for i in reservoirs["reservoir_id"]],
        weeks_to_threshold=[None if weeks[int(i)] is None else round(weeks[int(i)], 1) for i in reservoirs["reservoir_id"]])
    cols = st.columns(len(ALERT_ORDER))
    for c, level in zip(cols, ALERT_ORDER):
        c.metric(f"Reservoirs at {level}", int(sum(1 for a in alerts.values() if a == level)))
    t_res, t_set, t_leak = st.tabs(["Reservoirs", "Settlements at risk", "Leaks"])
    with t_res:
        st.dataframe(res_table[["name", "alert", "fill_pct", "norm_pct", "deviation_pp", "decline_pp_week", "weeks_to_threshold"]],
                     use_container_width=True, hide_index=True)
        pick = st.selectbox("Reservoir", reservoirs["name"])
        rid = int(reservoirs.loc[reservoirs["name"] == pick, "reservoir_id"].iloc[0])
        st_ = status[rid]
        o = observations[observations["reservoir_id"] == rid].sort_values("obs_date")
        left, right = st.columns(2)
        left.subheader("Fill and seasonal norm (%)")
        ui.chart("line", o.set_index("obs_date")[["fill_pct", "season_norm_pct"]].rename(columns={"fill_pct": "fill", "season_norm_pct": "seasonal norm"}),
                 "date (week)", "fill (% of total capacity)", "SIMULATED data (generate_data.py)")
        right.subheader("Trend forecast with interval (%)")
        ui.chart("line", forecast(st_, horizon_weeks=8).set_index("week_ahead")[["lower", "central", "upper"]],
                 "weeks ahead", "fill (% of total capacity)", "SIMULATED data; linear trend with an interval")
        w = st_["weeks_to_threshold"]
        if w is None:
            st.info("The reservoir is not falling over the chosen window; no threshold crossing is expected.")
        else:
            lo, hi = st_["weeks_min"], st_["weeks_max"]
            hi_txt = "no upper bound" if hi is None else f"{hi:.1f}"
            st.write(f"**Alert: {st_['alert_level'].upper()}.** At {st_['rate_pp_week']:.2f} pp per week the reservoir reaches "
                     f"{settings.critical_fill_pct:.0f}% in about **{w:.1f} weeks** (range {lo:.1f} to {hi_txt} weeks).")
    with t_set:
        st.dataframe(risk[["rank", "name", "risk_class", "risk_score", "exposure_pct", "worst_reservoir_alert", "weeks_to_threshold", "population"]],
                     use_container_width=True, hide_index=True)
        sel = st.selectbox("Explain a settlement", risk["name"])
        st.info(explain(risk[risk["name"] == sel].iloc[0]))
        st.caption("Score = 100 x exposure x (0.7 + 0.2 x population term + 0.1 x critical facility). "
                   "Exposure = supply share x (1 - backup share) x alert factor (green 0, yellow 0.4, orange 0.7, red 1).")
    with t_leak:
        render_leaks(data_dir, settlements, links)
